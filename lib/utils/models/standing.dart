class Standing {
  final int id;
  final int position;
  final String team;
  final String crest;
  final int played;
  final int won;
  final int drawn;
  final int lost;
  final int goalDifference;
  final int points;

  Standing({
    required this.id,
    required this.position,
    required this.team,
    required this.crest,
    required this.played,
    required this.won,
    required this.drawn,
    required this.lost,
    required this.goalDifference,
    required this.points,
  });
}
